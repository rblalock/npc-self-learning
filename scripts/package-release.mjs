import { cp, mkdir, readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const version=JSON.parse(await readFile(join(root,'package.json'),'utf8')).version;
const out=join(root,'target/releases'),stage=join(out,`stage-${version}`);
await mkdir(out,{recursive:true});await mkdir(stage,{recursive:true});
await cp(join(root,'apps/arena/public/wasm'),join(root,'packages/browser/wasm'),{recursive:true});
await cp(join(root,'LICENSE'),join(root,'packages/browser/LICENSE'));
const packed=JSON.parse(execFileSync('npm',['pack','--json','--pack-destination',out],{cwd:join(root,'packages/browser'),encoding:'utf8'}))[0].filename;
const browser=join(stage,`tactical-air-browser-${version}`);await mkdir(browser,{recursive:true});
await cp(join(root,'examples/browser-guard'),browser,{recursive:true});
await cp(join(root,'packages/browser/dist'),join(browser,'sdk'),{recursive:true});
await cp(join(root,'apps/arena/public/wasm'),join(browser,'wasm'),{recursive:true});
await cp(join(root,'LICENSE'),join(browser,'LICENSE'));
await cp(join(root,'docs/releases/quickstart.md'),join(browser,'README.md'));
const browserName=`tactical-air-browser-${version}.tar.gz`;
execFileSync('tar',['-czf',join(out,browserName),'-C',stage,`tactical-air-browser-${version}`]);
const sourceName=`tactical-air-source-${version}.tar.gz`;
const paths=['Cargo.toml','Cargo.lock','package.json','package-lock.json','tsconfig.json','tsconfig.sdk.json','README.md','LICENSE','DESIGN.md','PRODUCT.md','crates','packages/browser','apps/arena','apps/microsite/src','apps/microsite/README.md','scripts','docs','examples'];
execFileSync('tar',['--exclude=node_modules','--exclude=.DS_Store','--exclude=docs/releases/release-0.3.0.json','--exclude=docs/releases/validation-0.3.0.json','-czf',join(out,sourceName),'-C',root,...paths]);
const native=join(stage,`tactical-air-macos-arm64-${version}`);await mkdir(native,{recursive:true});
for(const name of ['libtactical_air_ffi.dylib','libtactical_air_ffi.a'])await cp(join(root,'target/release',name),join(native,name));
await cp(join(root,'crates/tactical-air-ffi/include/tactical_air.h'),join(native,'tactical_air.h'));
await cp(join(root,'LICENSE'),join(native,'LICENSE'));
await cp(join(root,'docs/contract.md'),join(native,'contract.md'));
await writeFile(join(native,'README.txt'),'Tactical Air '+version+'\nExperimental C ABI binary for macOS arm64 only.\nCompile your host against tactical_air.h; link -ltactical_air_ffi.\nSet your runtime library search path to the library directory.\nSource and other platform build instructions are in the source bundle.\nNo Unity, Godot, or Unreal plugin is included.\n');
const nativeName=`tactical-air-macos-arm64-${version}.tar.gz`;
execFileSync('tar',['-czf',join(out,nativeName),'-C',stage,`tactical-air-macos-arm64-${version}`]);
const files=[];
for(const name of [browserName,sourceName,packed,nativeName]){const b=await readFile(join(out,name));files.push({name,bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')});}
const manifest={schema:1,version,createdAt:new Date().toISOString(),license:'MIT',status:'experimental',registryPublication:'Not published to npm or crates.io; install from the downloadable source or npm tarball.',files};
await writeFile(join(out,'SHA256SUMS'),files.map(f=>`${f.sha256}  ${f.name}`).join('\n')+'\n');
await writeFile(join(out,'release.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(join(root,'docs/releases/release-0.3.0.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify(manifest,null,2));
